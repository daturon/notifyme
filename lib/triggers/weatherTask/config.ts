import { z } from "zod";

// Координаты вместо геокодирования по названию населённого пункта (задание
// прямо оставляет выбор: "широта/долгота или название с геокодированием").
// Выбраны координаты:
// - Open-Meteo forecast API в любом случае принимает только lat/lon —
//   геокодирование по имени было бы отдельным запросом (Open-Meteo Geocoding
//   API) со своей точкой отказа и неоднозначностью (несколько посёлков с
//   одинаковым названием, необходимость выбора из списка кандидатов);
// - приложение однопользовательское, локация задаётся один раз при создании
//   события и почти никогда не меняется — разовый ручной ввод координат
//   (с любой карты или сайта вроде latlong.net) не создаёт заметных
//   неудобств и не требует держать сетевой вызов геокодера в критическом
//   пути создания события.
// label — опциональное отображаемое имя (например "Жлобин, дача"), не
// участвует в запросе к API, только для UI.
export const weatherTaskConfigSchema = z.object({
  location: z.object({
    lat: z.number().min(-90).max(90),
    lon: z.number().min(-180).max(180),
    label: z.string().trim().min(1).optional(),
  }),
  // Раздел 4.3 ТЗ: прогноз на 5-7 дней вперёд.
  forecastDays: z.number().int().min(5).max(7).default(7),
});

export type WeatherTaskConfig = z.infer<typeof weatherTaskConfigSchema>;
